/* ДЗ 2. Свойства функции: опиши семь функций + задачи-ловушки «x или y». */
(function () {
  "use strict";
  var h = UI.h, m = UI.m, INF = Infinity;

  /* Новые «горки»: вершины (−3; 3) и (1; −2), нули −5, −1, 3 */
  var HILLS2 = { f: Describe.spline([-6, -5, -3, -1, 1, 3, 5], [-1, 0, 3, 0, -2, 0, 2]), a: -6, b: 5, crit: [-3, 1], zeros: [-5, -1, 3], view: [[-7.5, 6.5], [-3.5, 4.5]] };

  var FUNCS = [
    { id: "f1", level: 1, xp: 20, spec: HILLS2,
      q: "<p>Функция задана графиком на отрезке [−6; 5]. Опиши все её свойства.</p>" },
    { id: "f2", level: 1, xp: 20, spec: { f: function (x) { return -2 * x + 4; }, crit: [], zeros: [2], formula: "-2x+4" },
      q: "<p>Прямая " + m("y=-2x+4") + ". Опиши её свойства. Подсказка: прямую не надо обрезать — она идёт бесконечно в обе стороны.</p>" },
    { id: "f3", level: 2, xp: 25, spec: { f: function (x) { return x * x - 2 * x - 3; }, crit: [1], zeros: [-1, 3], formula: "x^2-2x-3" },
      q: "<p>Парабола " + m("y=x^2-2x-3") + ". Опиши её свойства.</p>" },
    { id: "f4", level: 2, xp: 25, spec: { f: function (x) { return Math.abs(x + 1) - 2; }, crit: [-1], zeros: [-3, 1], formula: "|x+1|-2" },
      q: "<p>Функция " + m("y=|x+1|-2") + " — «уголок». Опиши её свойства.</p>" },
    { id: "f5", level: 3, xp: 30, spec: { f: function (x) { return 4 - x * x; }, a: -3, b: 2, crit: [0], zeros: [-2, 2] },
      q: "<p>Функция " + m("y=4-x^2") + ", но только на отрезке " + m("[-3; 2]") + ". Опиши её свойства. Осторожно: концы отрезка тоже могут оказаться самыми высокими или низкими точками.</p>" },
    { id: "f6", level: 3, xp: 30, spec: { f: function (x) { return x < -4 ? NaN : Math.sqrt(x + 4) - 1; }, a: -4, crit: [], zeros: [-3], formula: "sqrt(x+4)-1" },
      q: "<p>Функция " + m("y=sqrt(x+4)-1") + ". Опиши её свойства. Подумай: при каких x корень вообще можно извлечь?</p>" },
    { id: "f7", level: 3, xp: 30, spec: { f: function (x) { return x === 0 ? NaN : 6 / x; }, holes: [0], crit: [], zeros: [], formula: "6/x",
      over: { E: [{ a: -INF, b: 0, ai: false, bi: false }, { a: 0, b: INF, ai: false, bi: false }] }, view: [[-8.5, 8.5], [-6, 6]] },
      q: "<p>Гипербола " + m("y=6/x") + ". Опиши её свойства. Самая хитрая: здесь есть x, который в машинку закидывать нельзя.</p>" }
  ];

  var STEPS = [
    "<b>План.</b> Иди по полям сверху вниз — это порядок из учебника. Сначала смотришь по горизонтали (D), потом по вертикали (E), потом едешь слева направо и отмечаешь всё остальное.",
    "Ошибся — под полем появится объяснение, что не так. После двух неудачных проверок можно подсмотреть ответы, но опыта будет вдвое меньше."
  ];

  function render(root) {
    var s1 = UI.section("Часть 1. Опиши функцию", "Семь функций — от простых к хитрым. Для каждой заполни 9 полей по плану: D, E, нули, знаки, рост и спад, наибольшее и наименьшее.");
    s1.appendChild(UI.callout("tip", "<p>" + STEPS[0] + "</p><p style=\"margin-top:8px\">" + STEPS[1] + "</p>"));
    s1.appendChild(h("p", { class: "muted", html: "Не помнишь, как писать скобки и ∞? Загляни в <a href=\"#/theory\">шпаргалку</a>, раздел «Как записывать ответы»." }));
    var t1 = h("div", { class: "tasks" });
    FUNCS.forEach(function (F, i) {
      t1.appendChild(Describe.card(F.spec, { id: "hw2:" + F.id, xp: F.xp, level: F.level, badge: "Функция " + (i + 1) + " из " + FUNCS.length, q: F.q }));
    });
    s1.appendChild(t1);
    root.appendChild(s1);

    var s2 = UI.section("Часть 2. Ловушки «x или y»", "Короткие задачи на то, что путают все.");
    var t2 = h("div", { class: "tasks" });
    var hillsPlot = function () {
      return { x: [-7.5, 6.5], y: [-3.5, 4.5], unitGrid: true, layers: [
        { type: "fn", f: HILLS2.f, color: "#d18f00", width: 3.5, domain: [-6, 5] },
        { type: "point", x: -6, y: -1, color: "#d18f00", r: 5 }, { type: "point", x: 5, y: 2, color: "#d18f00", r: 5 }] };
    };
    t2.appendChild(App.task({
      id: "hw2:t1", level: 1, xp: 10, kind: "number", plot: hillsPlot(),
      q: "<p>Это функция 1 из первой части. Найди её <b>наибольшее значение</b>.</p>",
      check: function (v) {
        var n = UI.parseNumber(v);
        if (isNaN(n)) return "Нужно число";
        if (Iv.eq(n, -3)) return "−3 — это x самой высокой точки. А значение функции — её высота y";
        return Iv.eq(n, 3);
      },
      hints: ["Значение — это y. Найди самую высокую точку и посмотри на её высоту."],
      solution: "Самая высокая точка (−3; 3). Наибольшее значение — её y, то есть 3."
    }));
    t2.appendChild(App.task({
      id: "hw2:t2", level: 2, xp: 15, kind: "number", prefix: "x =", plot: hillsPlot(),
      q: "<p>А теперь наоборот: <b>при каком x</b> эта функция принимает наименьшее значение?</p>",
      check: function (v) {
        var n = UI.parseNumber(v);
        if (isNaN(n)) return "Нужно число";
        if (Iv.eq(n, -2)) return "−2 — это само наименьшее значение (высота). А спрашивают, при каком x оно достигается";
        if (Iv.eq(n, -6)) return "В точке x = −6 высота −1. А есть точка ниже";
        return Iv.eq(n, 1);
      },
      hints: ["Найди самую низкую точку графика. Спрашивают её x — то, что под ней на горизонтальной оси."],
      solution: "Самая низкая точка (1; −2). Наименьшее значение −2 достигается при x = 1. Читай вопрос внимательно: «чему равно наименьшее значение» — это y, «при каком x» — это x."
    }));
    t2.appendChild(App.task({
      id: "hw2:t3", level: 2, xp: 15, kind: "choice",
      q: "<p>Функция " + m("y=x^2-4x+5") + ", то есть " + m("y=(x-2)^2+1") + ". Чему равно её наименьшее значение?</p>",
      options: ["1", "2", "(2; 1)", "наименьшего нет"], answer: 0,
      hints: ["Вершина параболы (2; 1), ветви вверх. Значение — это высота вершины."],
      solution: "Вершина (2; 1) — самая низкая точка. Наименьшее значение — её y, то есть 1. «2» — это x вершины, а «(2; 1)» — вся точка, а нужно одно число."
    }));
    t2.appendChild(App.task({
      id: "hw2:t4", level: 2, xp: 15, kind: "choice",
      q: "<p>У какой функции " + m("E(f)=[0; +∞)") + "?</p>",
      options: [m("y=x^2-4"), m("y=|x-3|"), m("y=-x^2"), m("y=1/x")], answer: 1,
      hints: ["E — это высоты. Представь каждый график: какая у него самая низкая точка и уходит ли он вверх?"],
      solution: "|x − 3| ≥ 0, ноль достигается при x = 3, а вверх ветви уходят бесконечно: E = [0; +∞). У x² − 4 самая низкая высота −4: E = [−4; +∞). У −x² всё наоборот: E = (−∞; 0]. У 1/x высоты все, кроме 0."
    }));
    t2.appendChild(App.task({
      id: "hw2:t5", level: 3, xp: 20, kind: "choice",
      q: "<p>Как правильно записать, где убывает " + m("y=6/x") + "?</p>",
      options: ["(−∞; 0) ∪ (0; +∞)", "(−∞; 0) и (0; +∞)", "(−∞; +∞)", "x > 0"], answer: 1,
      hints: ["Сравни f(−1) и f(1). x вырос — а что с y? Можно ли сказать, что функция убывает на всём объединении?"],
      solution: "f(−1) = −6, f(1) = 6: x вырос, и y вырос. Значит, на объединении (−∞; 0) ∪ (0; +∞) функция не убывает. Она убывает на каждом промежутке отдельно — поэтому пишут через «и»."
    }));
    t2.appendChild(App.task({
      id: "hw2:t6", level: 3, xp: 20, kind: "multi", badge: "Найди ошибки",
      q: "<p>Петя описал функцию " + m("y=x^2-1") + ". Отметь <b>все</b> строчки, где он ошибся.</p>",
      options: ["D(f) = (−∞; +∞)", "E(f) = (−∞; +∞)", "Нули: −1; 1", "f(x) > 0 при x ∈ (−1; 1)", "Убывает на (−∞; 0]", "Наименьшее значение: 0"],
      answer: [1, 3, 5],
      hints: ["Нарисуй: это y = x², опущенная на 1 вниз. Вершина (0; −1).", "Между нулями −1 и 1 график выше или ниже оси x?"],
      solution: "Ошибки: E(f) = [−1; +∞) — ниже вершины график не опускается. Между нулями парабола ниже оси: там f(x) < 0, а f(x) > 0 на (−∞; −1) ∪ (1; +∞). Наименьшее значение — высота вершины, −1, а 0 — это её x. Остальное верно."
    }));
    var opts = [
      Describe.spline([-4, -2, 0, 2, 4], [2, 0, -3, 0, 2]),
      Describe.spline([-4, -1, 1, 3, 4], [-2, 0, 3, 0, -1]),
      Describe.spline([-4, -2, 0, 2, 4], [-2, 0, 3, 0, -2]),
      Describe.spline([-5, -2, 0, 2, 5], [-3, 0, 3, 0, -3])
    ].map(function (f, i) { return UI.mini(f, { color: Plot.PALETTE[i], r: 5, h: 150 }); });
    t2.appendChild(App.task({
      id: "hw2:t7", level: 3, xp: 20, kind: "choice", grid: true, badge: "Найди по описанию",
      q: "<p>Какой график подходит под описание?</p><ul style=\"margin:6px 0 0;padding-left:22px\"><li>D(f) = [−4; 4], E(f) = [−2; 3]</li><li>нули: −2 и 2</li><li>возрастает на [−4; 0], убывает на [0; 4]</li></ul>",
      options: opts, answer: 2,
      hints: ["Сначала проверь нули: где графики пересекают ось x? Потом — где начинается и кончается график."],
      solution: "Первый график сначала убывает. У второго нули −1 и 3. У четвёртого D = [−5; 5] и E = [−3; 3]. Подходит третий."
    }));
    s2.appendChild(t2);
    root.appendChild(s2);

    root.appendChild(h("div", { class: "block" },
      h("h2", { class: "block__title", text: "Мало? Тренируйся без конца" }),
      h("p", { class: "block__intro", html: "В тренажёре каждый раз новый график: горки, параболы, уголки, корни, гиперболы." }),
      h("div", null, h("a", { class: "btn btn--primary", href: "#/train", text: "В тренажёр «Опиши график» →" }))));
  }

  App.page({
    id: "hw2", order: 4, title: "ДЗ 2. Свойства функции", subtitle: "Опиши 7 функций по плану + 7 задач-ловушек «x или y»",
    color: "var(--green)", icon: "2", total: FUNCS.length + 7, render: render
  });
})();

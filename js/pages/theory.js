/* Шпаргалка: коротко темы 1–3 и образец описания функции. */
(function () {
  "use strict";
  var h = UI.h, m = UI.m;

  /* «Горки» с основного сайта — ученик их уже видел */
  var HILLS = { f: UI.smooth([[-7, -3], [-5, 3], [-1, -3], [3, 3], [5, 1]]), a: -7, b: 5, crit: [-5, -1, 3], zeros: [-6, -3, 1] };

  function cards(list) {
    var box = h("div", { class: "cheat" });
    list.forEach(function (c) { box.appendChild(h("div", { class: "cheat__item", html: (c[0] ? '<span class="m">' + c[0] + "</span>" : "") + c[1] })); });
    return box;
  }

  function sample() {
    var A = Describe.analyze(HILLS);
    var pb = UI.plotBox({ x: [-8, 6], y: [-4.5, 4.5], unitGrid: true });
    var table = h("table", { class: "vtable desc-table" });
    Describe.ALL.forEach(function (k) {
      var F = Describe.FIELDS[k];
      table.appendChild(h("tr", null,
        h("th", null, h("span", { class: "m", text: F.label })),
        h("td", { class: "muted", text: F.name }),
        h("td", null, h("b", { text: Describe.answerText(k, A) }))));
    });
    UI.later(function () {
      var P = pb.mount();
      P.layers = [
        { type: "fn", f: HILLS.f, color: "#d18f00", width: 3.5, domain: [-7, 5] },
        { type: "point", x: -7, y: -3, color: "#d18f00", r: 5 }, { type: "point", x: 5, y: 1, color: "#d18f00", r: 5 }
      ];
      P.draw();
    });
    return h("div", { class: "split split--even" }, pb.el, h("div", { class: "scroll-x" }, table));
  }

  function render(root) {
    var s1 = UI.section("1. Функция — это машинка");
    s1.appendChild(UI.theory(
      "<p>Закидываешь число " + m("x") + " — внутри срабатывает правило — выпадает <b>ровно одно</b> число " + m("y") + ".</p>" +
      "<ul><li>" + m("x") + " — <b>аргумент</b>, то, что закидываешь.</li>" +
      "<li>" + m("y") + " — <b>значение функции</b>, то, что выпало.</li>" +
      "<li>" + m("f(3)=7") + " — «эф от трёх равно семи»: закинули 3, выпало 7.</li></ul>"));
    s1.appendChild(UI.callout("warn", "<p><b>Один x — один y.</b> Если на один и тот же x машинка выдаёт разные y — это не функция. А разные x с одинаковым y — нормально: у " + m("y=x^2") + " и " + m("f(2)") + ", и " + m("f(-2)") + " равны 4.</p>"));
    s1.appendChild(cards([
      ["Формулой", m("y=x^2-1") + ": подставил x — посчитал y."],
      ["Таблицей", "x: 1, 2, 3 → y: 5, 8, 11."],
      ["Графиком", "Над x поднимаешься до линии и читаешь высоту."],
      ["Словами", "«Квадрат числа, уменьшенный на 1»."]
    ]));
    s1.appendChild(UI.theory("<p><b>Две задачи-машинки.</b> «Найди " + m("f(-2)") + "» — подставь −2 вместо каждого x. «При каком x " + m("f(x)=9") + "» — машинка наоборот: реши уравнение.</p>" +
      "<p><b>Когда машинка ломается.</b> Делить на ноль нельзя, корень из отрицательного числа не извлекается. У " + m("y=5/(x-2)") + " число 2 закидывать нельзя: знаменатель станет нулём.</p>"));
    root.appendChild(s1);

    var s2 = UI.section("2. График — портрет функции");
    s2.appendChild(UI.theory("<p><b>График</b> — все точки " + m("(x; f(x))") + ". Берёшь x, считаешь y, ставишь точку. Сначала x (по горизонтали), потом y (по вертикали).</p>"));
    s2.appendChild(UI.callout("fun", "<p class=\"m-big\">Точка (a; b) лежит на графике ⇔ b = f(a)</p><p>Подставь x точки в формулу. Вышел y точки — лежит. Не вышел — мимо.</p>"));
    s2.appendChild(cards([
      ["f(a) по графику", "Найди a на оси x, поднимись (или опустись) до графика, посмотри высоту."],
      ["f(x) = b по графику", "Проведи горизонтальную прямую y = b. Где она пересекает график — смотри вниз на x. Это корни."],
      ["Ось y", "У всех её точек x = 0. Подставь x = 0 — получишь, где график пересекает ось y."],
      ["Ось x", "У всех её точек y = 0. Реши f(x) = 0 — получишь, где график пересекает ось x."]
    ]));
    root.appendChild(s2);

    var s3 = UI.section("3. График — это карта горной дороги", "Едем слева направо, как по трассе. Всё, что спрашивают про свойства, — это вопросы водителю.");
    s3.appendChild(cards([
      ["D(f)", "<b>Область определения.</b> По каким x вообще можно ехать — где дорога существует."],
      ["E(f)", "<b>Область значений.</b> На каких высотах побывала машина — от самой низкой до самой высокой."],
      ["f(x)=0", "<b>Нули.</b> Где дорога пересекает «уровень моря» — ось x."],
      ["f(x)>0", "<b>Промежутки знакопостоянства.</b> Где едем выше моря (функция положительна), где ниже (отрицательна)."],
      ["↗ ↘", "<b>Возрастание и убывание.</b> Где в горку, где с горки. Отвечаем промежутками x."],
      ["max, min", "<b>Наибольшее и наименьшее.</b> Самая высокая и самая низкая точка — это значения y."]
    ]));
    s3.appendChild(UI.callout("warn", "<p><b>Главная ловушка.</b> Промежутки возрастания и знаков записывают через <b>x</b> (где по горизонтали), а наибольшее значение — это <b>y</b> (на какой высоте). Путают все. Ты теперь не будешь.</p>"));
    root.appendChild(s3);

    var s4 = UI.section("Образец: как описать функцию", "Вот «Горки» с урока. Так выглядит полное описание — в домашке будешь делать такое сам.");
    s4.appendChild(sample());
    root.appendChild(s4);

    var s5 = UI.section("Как записывать ответы на сайте");
    s5.appendChild(cards([
      ["[ ]  и  ( )", "Квадратная скобка — конец входит (закрашенная точка). Круглая — не входит (выколотая точка, ноль в знаках, бесконечность)."],
      ["∞", "Бесконечность пиши как <span class=\"kbd\">+∞</span>, <span class=\"kbd\">−∞</span> или словом <span class=\"kbd\">inf</span>. Скобка у неё всегда круглая: <span class=\"kbd\">(−∞; 3]</span>."],
      ["∪", "Объединение кусков для D, E и знаков: <span class=\"kbd\">(−6; −3) ∪ (1; 5]</span>. Можно буквой <span class=\"kbd\">U</span>."],
      ["и", "Промежутки возрастания и убывания пишут через «и», <b>не через ∪</b>: <span class=\"kbd\">[−7; −5] и [−1; 3]</span>."],
      ["нет", "Нет нулей, нет наибольшего значения, функция нигде не возрастает — пиши <span class=\"kbd\">нет</span>."],
      ["x < 3", "Можно и неравенством: <span class=\"kbd\">x < 3</span>, <span class=\"kbd\">−2 <= x < 5</span>, <span class=\"kbd\">x ≠ 0</span>. Все числа — <span class=\"kbd\">все числа</span>."]
    ]));
    s5.appendChild(UI.callout("tip", "<p>Под полями ввода есть кнопки со скобками, ∞ и ∪ — удобно с телефона. Кнопка <b>?</b> рядом с каждым полем подсказывает, где на графике искать ответ.</p>"));
    root.appendChild(s5);
  }

  App.page({
    id: "theory", order: 1, title: "Шпаргалка", subtitle: "Функция, график и шесть свойств — коротко, на одной странице",
    color: "var(--yellow)", icon: "📖", ring: "→", render: render
  });
})();
